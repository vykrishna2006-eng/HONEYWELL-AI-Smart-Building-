"""
=========================================================
Prediction CRUD Operations
=========================================================
"""

from sqlalchemy.orm import Session

from database.models import Prediction
from database.schemas.prediction_schema import (
    PredictionCreate,
    PredictionUpdate,
)

# =====================================================
# Standard CRUD Operations
# =====================================================

def create_prediction(
    db: Session,
    prediction: PredictionCreate,
):
    """
    Create a prediction manually through the CRUD API.
    """

    db_prediction = Prediction(
        **prediction.model_dump()
    )

    db.add(db_prediction)
    db.commit()
    db.refresh(db_prediction)

    return db_prediction


def get_prediction(
    db: Session,
    prediction_id: int,
):
    """
    Retrieve a prediction by ID.
    """

    return (
        db.query(Prediction)
        .filter(Prediction.id == prediction_id)
        .first()
    )


def get_predictions(
    db: Session,
):
    """
    Retrieve all predictions.
    """

    return db.query(Prediction).all()


def update_prediction(
    db: Session,
    prediction_id: int,
    prediction_update: PredictionUpdate,
):
    """
    Update an existing prediction.
    """

    prediction = get_prediction(
        db,
        prediction_id,
    )

    if prediction is None:
        return None

    update_data = prediction_update.model_dump(
        exclude_unset=True
    )

    for key, value in update_data.items():
        setattr(prediction, key, value)

    db.commit()
    db.refresh(prediction)

    return prediction


def delete_prediction(
    db: Session,
    prediction_id: int,
):
    """
    Delete a prediction.
    """

    prediction = get_prediction(
        db,
        prediction_id,
    )

    if prediction is None:
        return None

    db.delete(prediction)
    db.commit()

    return prediction


# =====================================================
# Machine Learning Operations
# =====================================================

def create_ml_prediction(
    db: Session,
    sensor_id: int,
    energy_prediction: float,
    comfort_prediction: float,
    confidence: float = 1.0,
    model_version: str = "RandomForest_v1.0",
):
    """
    Save a prediction generated by the ML model.
    """

    prediction = Prediction(
        sensor_id=sensor_id,
        energy_prediction=energy_prediction,
        comfort_prediction=comfort_prediction,
        confidence=confidence,
        model_version=model_version,
    )

    db.add(prediction)
    db.commit()
    db.refresh(prediction)

    return prediction


def get_latest_prediction(
    db: Session,
):
    """
    Get the most recent ML prediction.
    """

    return (
        db.query(Prediction)
        .order_by(Prediction.prediction_time.desc())
        .first()
    )


def get_predictions_by_sensor(
    db: Session,
    sensor_id: int,
):
    """
    Get all predictions for a sensor.
    """

    return (
        db.query(Prediction)
        .filter(Prediction.sensor_id == sensor_id)
        .order_by(Prediction.prediction_time.desc())
        .all()
    )


def get_prediction_history(
    db: Session,
    sensor_id: int | None = None,
):
    """
    Get prediction history.
    """

    query = db.query(Prediction)

    if sensor_id is not None:
        query = query.filter(
            Prediction.sensor_id == sensor_id
        )

    return (
        query.order_by(
            Prediction.prediction_time.desc()
        )
        .all()
    )